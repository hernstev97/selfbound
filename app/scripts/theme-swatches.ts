// Swatches of the bundled themes for the picker in settings, so the list works without the theme
// files. Regenerate after changing a theme or map.ts:
//   node app/scripts/theme-swatches.ts
// app/test/look.test.ts checks that the file matches the mapping.
import { readFileSync, writeFileSync } from 'node:fs';
import { BUILTIN } from '../src/themes/list.ts';
import { mapTheme } from '../src/lib/look/map.ts';
import { readTheme } from '../src/lib/look/vscode.ts';

const lines: string[] = [];
for (const { id, type } of BUILTIN) {
  const text = readFileSync(new URL(`../src/themes/${id}/theme.json`, import.meta.url), 'utf8');
  const { vars } = mapTheme(readTheme(text, { typeHint: type }));
  const colors = [vars['bg-app'], vars['bg-panel'], vars.text, vars.accent, vars['syn-keyword'], vars['syn-string'], vars['syn-func']];
  lines.push(`  '${id}': [${colors.map((c) => `'${c}'`).join(', ')}],`);
}
const out = `// Generated by app/scripts/theme-swatches.ts, do not edit by hand.
// Per theme: sidebar, content, text, accent, keyword, string, function.
export const SWATCHES: Record<string, string[]> = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../src/themes/swatches.ts', import.meta.url), out);
console.log(`${lines.length} themes`);
